#!/usr/bin/env python3
"""
Add the browser-tab icon and link-preview tags to every page of the site.

Each page gets one managed block just before </head>:
  - favicon (assets/favicon.svg + favicon-32.png) and apple-touch-icon
  - Open Graph / Twitter tags, so a link pasted into LinkedIn, Slack, Teams
    or X shows a title card with assets/og-image.png

The title and description come from the page itself: <title>, then
<meta name="description">, else the page subtitle (.page-sub / .subtitle),
else the site default. Re-running replaces the block, so it is safe to run
after any change; build_project.py runs it for you.

Skipped: redirect stubs (meta refresh) and the MkDocs theme files.

Usage:
    python3 site_meta.py               # add / refresh the block on every page
    python3 site_meta.py --check       # exit 1 if any page is missing or stale
"""
import argparse
import html
import re
import sys
from pathlib import Path

SITE_URL = "https://natsuichigo.github.io/mark/"
SITE_NAME = "Mark Bam — Systems Engineer II · DevOps & Platform Engineer"
DEFAULT_DESC = ("Portfolio of Mark Bam: 10+ years in enterprise IT. Ansible Automation Platform, "
                "Terraform, AWS and VMware; golden image pipelines, Ansible Execution Environments "
                "and a Kubernetes home lab.")
IMAGE = "assets/og-image.png"
# Bump after re-rendering og-image.png so link previews stop showing the cached image.
IMAGE_VERSION = "2"

START = "<!-- site-meta: generated by md-to-docs/scripts/site_meta.py, do not edit -->"
END = "<!-- /site-meta -->"
BLOCK_RE = re.compile(r"[ \t]*" + re.escape(START) + r".*?" + re.escape(END) + r"\n?", re.S)


def _text(fragment):
    return html.unescape(re.sub(r"<[^>]+>", "", fragment)).strip()


def _attr(value):
    return html.escape(" ".join(value.split()), quote=True)


def page_info(src):
    title = re.search(r"<title>(.*?)</title>", src, re.S)
    title = _text(title.group(1)) if title else SITE_NAME
    desc = re.search(r'<meta name="description" content="([^"]*)"', src)
    if desc:
        desc = html.unescape(desc.group(1))
    else:
        sub = re.search(r'<p class="(?:page-sub|subtitle)">(.*?)</p>', src, re.S)
        desc = _text(sub.group(1)) if sub and _text(sub.group(1)) else DEFAULT_DESC
    return title, desc


def render_block(rel_path, src):
    """The managed block for the page at rel_path (relative to the deploy root)."""
    depth = len(Path(rel_path).parts) - 1
    up = "./" if depth == 0 or "<base href=" in src else "../" * depth
    url = SITE_URL + re.sub(r"(^|/)index\.html$", r"\1", rel_path)
    title, desc = page_info(src)
    lines = [
        START,
        f'<link rel="icon" href="{up}assets/favicon.svg" type="image/svg+xml">',
        f'<link rel="icon" href="{up}assets/favicon-32.png" sizes="32x32" type="image/png">',
        f'<link rel="apple-touch-icon" href="{up}assets/apple-touch-icon.png">',
        '<meta property="og:type" content="website">',
        f'<meta property="og:site_name" content="{_attr(SITE_NAME)}">',
        f'<meta property="og:title" content="{_attr(title)}">',
        f'<meta property="og:description" content="{_attr(desc)}">',
        f'<meta property="og:url" content="{url}">',
        f'<meta property="og:image" content="{SITE_URL}{IMAGE}?v={IMAGE_VERSION}">',
        '<meta property="og:image:width" content="1200">',
        '<meta property="og:image:height" content="630">',
        f'<meta property="og:image:alt" content="{_attr(SITE_NAME)}">',
        '<meta name="twitter:card" content="summary_large_image">',
        END,
    ]
    return "".join("    " + l + "\n" for l in lines)


def apply(rel_path, src):
    """src with its block added or refreshed."""
    clean = BLOCK_RE.sub("", src)
    block = render_block(rel_path, clean)
    return re.sub(r"([ \t]*)</head>", lambda m: block + m.group(1) + "</head>", clean, count=1)


def site_pages(deploy_root):
    for p in sorted(deploy_root.rglob("*.html")):
        rel = p.relative_to(deploy_root).as_posix()
        if rel.startswith("docs/assets/"):
            continue
        src = p.read_text(encoding="utf-8")
        if 'http-equiv="refresh"' in src or "</head>" not in src:
            continue
        yield rel, p, src


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--repo-root", default=".", help="Path to the mark repo checkout (default: .)")
    ap.add_argument("--deploy-dir", default="_deploy", help="Deploy folder to target (default: _deploy)")
    ap.add_argument("--check", action="store_true", help="Report only; exit 1 if any page is missing or stale")
    args = ap.parse_args()

    deploy_root = Path(args.repo_root) / args.deploy_dir
    if not deploy_root.is_dir():
        sys.exit(f"error: {deploy_root} not found — is --repo-root correct?")
    missing_assets = [a for a in ("assets/favicon.svg", "assets/favicon-32.png",
                                  "assets/apple-touch-icon.png", IMAGE)
                      if not (deploy_root / a).is_file()]
    if missing_assets:
        print(f"  WARNING: missing image files: {', '.join(missing_assets)}")

    stale, total = [], 0
    for rel, path, src in site_pages(deploy_root):
        total += 1
        new = apply(rel, src)
        if new != src:
            stale.append(rel)
            if not args.check:
                path.write_text(new, encoding="utf-8")

    if args.check:
        if stale:
            print(f"  {len(stale)} of {total} pages missing or stale site-meta — run site_meta.py:")
            for rel in stale:
                print(f"    {rel}")
            return 1
        print(f"  site-meta current on all {total} pages")
        return 0
    print(f"  site-meta: updated {len(stale)} of {total} pages" if stale else f"  site-meta: all {total} pages current")
    return 0


if __name__ == "__main__":
    sys.exit(main())
