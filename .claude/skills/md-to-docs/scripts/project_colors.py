#!/usr/bin/env python3
"""
Generate _deploy/assets/project-colors.css: each case study's button colour,
taken from the main platform or application the project is built on
(Ansible -> Red Hat red, Kubernetes -> Kubernetes blue, ...).

Each project picks its colour with a "brand" key in its
_deploy/docs/<project>/_src/docs.config.json:

    "brand": "ansible"      a known tool name (see --list-tools)
    "brand": "#7b42bc"      or any hex colour

The colour is darkened, if needed, until white text on it is readable
(WCAG AA, 4.5:1). It is applied, by hub.css, to:
  - cards on Home / Projects that link to docs/<project>/
  - the project's own hub page (<body data-project="<project>">)
Projects without a "brand" keep the default blue.

Usage:
    python3 project_colors.py                 # regenerate the CSS
    python3 project_colors.py --check         # exit 1 if the CSS is out of date
    python3 project_colors.py --list-tools    # known tool names and colours
"""
import argparse
import json
import re
import sys
from pathlib import Path

# Official brand colours. Aliases point at the same entry.
TOOL_COLORS = {
    "ansible":        ("#EE0000", "Red Hat red"),
    "redhat":         ("#EE0000", "Red Hat red"),
    "rhel":           ("#EE0000", "Red Hat red"),
    "packer":         ("#02A8EF", "Packer blue"),
    "terraform":      ("#7B42BC", "Terraform purple"),
    "vault":          ("#FFD814", "Vault yellow"),
    "kubernetes":     ("#326CE5", "Kubernetes blue"),
    "k8s":            ("#326CE5", "Kubernetes blue"),
    "helm":           ("#0F1689", "Helm navy"),
    "openshift":      ("#EE0000", "Red Hat red"),
    "docker":         ("#2496ED", "Docker blue"),
    "podman":         ("#892CA0", "Podman purple"),
    "aws":            ("#FF9900", "AWS orange"),
    "azure":          ("#0078D4", "Azure blue"),
    "gcp":            ("#4285F4", "Google Cloud blue"),
    "github":         ("#24292F", "GitHub black"),
    "github-actions": ("#2088FF", "GitHub Actions blue"),
    "gitlab":         ("#FC6D26", "GitLab orange"),
    "jenkins":        ("#D24939", "Jenkins red"),
    "argocd":         ("#EF7B4D", "Argo orange"),
    "prometheus":     ("#E6522C", "Prometheus orange"),
    "grafana":        ("#F46800", "Grafana orange"),
    "traefik":        ("#24A1C1", "Traefik teal"),
    "vmware":         ("#607078", "VMware grey"),
    "vsphere":        ("#607078", "VMware grey"),
    "python":         ("#3776AB", "Python blue"),
    "windows":        ("#0078D4", "Windows blue"),
    "linux":          ("#333333", "Linux black"),
    "claude":         ("#D97757", "Claude clay"),
}

OUT_REL = Path("assets") / "project-colors.css"
MIN_CONTRAST = 4.5  # white text on the button

HEADER = """/* ═══════════════════════════════════════════════════════════════
   project-colors.css  —  GENERATED by md-to-docs/scripts/project_colors.py
   Do not edit by hand. Set "brand" in docs/<project>/_src/docs.config.json
   and re-run the script (build_project.py runs it for you).

   Each block sets --proj / --proj-rgb for one case study; hub.css uses them
   for that project's buttons and icon badges, falling back to the default
   blue where they are not set.
   ═══════════════════════════════════════════════════════════════ */
"""


def _lum(rgb):
    c = [x / 255 for x in rgb]
    c = [x / 12.92 if x <= 0.03928 else ((x + 0.055) / 1.055) ** 2.4 for x in c]
    return 0.2126 * c[0] + 0.7152 * c[1] + 0.0722 * c[2]


def contrast_with_white(rgb):
    return 1.05 / (_lum(rgb) + 0.05)


def hex_to_rgb(h):
    h = h.lstrip("#")
    if len(h) == 3:
        h = "".join(ch * 2 for ch in h)
    return tuple(int(h[i:i + 2], 16) for i in (0, 2, 4))


def rgb_to_hex(rgb):
    return "#" + "".join(f"{v:02x}" for v in rgb)


def readable(rgb):
    """Darken (keeping the hue) until white text passes MIN_CONTRAST."""
    r, g, b = rgb
    while contrast_with_white((r, g, b)) < MIN_CONTRAST:
        r, g, b = (int(v * 0.97) for v in (r, g, b))
    return (r, g, b)


def resolve_brand(brand):
    """'ansible' or '#cc0000' -> (source hex, label). Raises ValueError if unknown."""
    b = str(brand).strip()
    if re.fullmatch(r"#?[0-9a-fA-F]{6}|#?[0-9a-fA-F]{3}", b):
        return ("#" + b.lstrip("#")).lower(), "custom colour"
    key = b.lower().replace(" ", "-")
    if key in TOOL_COLORS:
        return TOOL_COLORS[key][0].lower(), TOOL_COLORS[key][1]
    raise ValueError(f"unknown brand '{brand}' — use a hex colour or one of: "
                     + ", ".join(sorted(TOOL_COLORS)))


def project_block(project, brand):
    src, label = resolve_brand(brand)
    rgb = readable(hex_to_rgb(src))
    hx = rgb_to_hex(rgb)
    note = f"{brand} — {label} {src}" + (f", darkened to {hx} for white text" if hx != src else "")
    return (f"/* {project}: {note} */\n"
            f'.card:is([href*="docs/{project}/"], :has(a[href*="docs/{project}/"])),\n'
            f'body[data-project="{project}"] {{\n'
            f"    --proj: {hx}; --proj-rgb: {rgb[0]}, {rgb[1]}, {rgb[2]}; --proj-icon: #ffffff;\n"
            f"}}\n")


def load_brands(deploy_root):
    """{project: brand} for every set whose config has a "brand" key, sorted by name."""
    brands = {}
    for cfg in sorted((deploy_root / "docs").glob("*/_src/docs.config.json")):
        data = json.loads(cfg.read_text(encoding="utf-8"))
        if data.get("brand"):
            brands[cfg.parent.parent.name] = data["brand"]
    return brands


def generate(deploy_root):
    blocks = [project_block(p, b) for p, b in load_brands(deploy_root).items()]
    return HEADER + "\n" + "\n".join(blocks)


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--repo-root", default=".", help="Path to the mark repo checkout (default: .)")
    ap.add_argument("--deploy-dir", default="_deploy", help="Deploy folder to target (default: _deploy)")
    ap.add_argument("--check", action="store_true", help="Report only; exit 1 if the CSS is out of date")
    ap.add_argument("--list-tools", action="store_true", help="List the known tool names and exit")
    args = ap.parse_args()

    if args.list_tools:
        for name, (hx, label) in sorted(TOOL_COLORS.items()):
            out = rgb_to_hex(readable(hex_to_rgb(hx)))
            print(f"  {name:16} {hx.lower()}  {label}" + (f"  (buttons: {out})" if out != hx.lower() else ""))
        return 0

    deploy_root = Path(args.repo_root) / args.deploy_dir
    if not (deploy_root / "docs").is_dir():
        sys.exit(f"error: {deploy_root / 'docs'} not found — is --repo-root correct?")

    try:
        css = generate(deploy_root)
    except ValueError as e:
        sys.exit(f"error: {e}")
    out = deploy_root / OUT_REL
    current = out.read_text(encoding="utf-8") if out.is_file() else None

    if args.check:
        if current == css:
            print(f"  {OUT_REL} is up to date")
            return 0
        print(f"  {OUT_REL} is OUT OF DATE — run project_colors.py to regenerate it")
        return 1

    if current == css:
        print(f"  {OUT_REL}: unchanged")
    else:
        out.write_text(css, encoding="utf-8")
        print(f"  wrote {OUT_REL}")
    for project, brand in load_brands(deploy_root).items():
        src, label = resolve_brand(brand)
        print(f"    {project:28} {brand} ({label}) -> {rgb_to_hex(readable(hex_to_rgb(src)))}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
